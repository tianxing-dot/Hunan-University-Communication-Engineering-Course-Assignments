// 数字单词
#include<iostream>
using namespace std;

int main()
{
	char a;
	cin>>a;
	if (a=='0')
	    cout<<"Zero";
    else if (a=='1')
        cout<<"One";
    else if (a=='2')
        cout<<"Two";
    else if (a=='3')
        cout<<"Three";
    else if (a=='4')
        cout<<"Four";
    else if (a=='5')
        cout<<"Five";
    else if (a=='6')
        cout<<"Six";
    else if (a=='7')
        cout<<"Seven";
    else if (a=='8')
        cout<<"Eight";
    else if (a=='9')
        cout<<"Night";
    else
        cout<<"Other";
}
